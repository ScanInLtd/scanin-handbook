import assert from "node:assert/strict";
import { analyze, baselineAt, focusedReview, ironingOffset, gate, numeric, DAY, type Axis, type Event, type Sample } from "./site-audit-model";

const axes: Axis[] = [{ key: "HeightDisplacement", label: "Z", unit: "mm", jump: 100 }];
const t = Date.parse("2026-10-01");
const sample = (i: number, raw = 10, smooth: number | null = 0): Sample => ({ t: t + i * DAY / 4, raw: [raw], smooth: [smooth], suspect: false, reason: "", replay: false, worked: false });
const event = (time: number, initial: number, continuity = true): Event => ({ id: String(time), time, reason: continuity ? "iron" : "rebaseline", note: "", continuity, initial: { HeightDisplacement: initial }, createdAt: null });
const options = { from: t, now: t + 5 * DAY, window: 2 * DAY, type: "prism", expectsMA: true, partial: false, latest: t + 5 * DAY };
assert.equal(numeric(null), null);
assert.equal(numeric(""), null);
assert.equal(numeric("  "), null);
assert.equal(numeric("12.5"), 12.5);
assert.equal(numeric(Infinity), null);
assert.deepEqual(baselineAt([event(t, 10), event(t + DAY, 110)], {}, t + DAY), { HeightDisplacement: 110 });
assert.equal(gate([t, t + DAY], t + DAY, 2 * DAY, null), "sparse");
assert.equal(gate([t, t + DAY, t + 2 * DAY], t + 2 * DAY, 2 * DAY, null), "coverage");
assert.equal(gate(Array.from({ length: 9 }, (_, i) => t + i * DAY / 4), t + 2 * DAY, 2 * DAY, null), "candidate");
assert.equal(gate(Array.from({ length: 9 }, (_, i) => t + i * DAY / 4), t + 2 * DAY, 2 * DAY, t + 1.9 * DAY), "reset");
const points = Array.from({ length: 20 }, (_, i) => sample(i, i < 8 ? 10 : 110));
const corrected = analyze(points, axes, [event(t, 10), event(t + 2 * DAY, 110)], {}, options);
assert(corrected.days.every(d => d.raw[0] === 0));
assert(corrected.days.every(d => d.smooth[0] === 0));
assert.equal(corrected.shifts.length, 0);
assert.equal(corrected.counts.anyMA, 20);
const flagged = analyze([{ ...sample(0), suspect: true, reason: "manual-era" }, { ...sample(1), replay: true }, sample(2)], axes, [], { HeightDisplacement: 10 }, options);
assert.equal(flagged.counts.anyMA, 1);
assert.equal(flagged.counts.suspect, 1);
assert.equal(flagged.counts.replay, 1);
const missing = analyze([sample(0)], axes, [], {}, options);
assert.equal(missing.days[0].raw[0], null);
assert.equal(missing.counts.missingBaseline, 1);
const empty = analyze([], axes, [], {}, { ...options, latest: null });
assert.equal(empty.counts.eligible, 0);
assert(empty.findings.some(f => f.key === "no-data"));
const gap = analyze([sample(0), sample(20)], axes, [], { HeightDisplacement: 10 }, { ...options, latest: t + 5 * DAY });
assert.equal(gap.gaps.length, 1);
assert.equal(gap.gaps[0].trailing, false);
const sensor = (data: Sample[], events: Event[] = []) => ({ id: "test", type: "prism", axes, expectsMA: true, partial: false, first: t, latest: data.at(-1)?.t ?? null, events, analysis: analyze(data, axes, events, { HeightDisplacement: 10 }, { ...options, now: t + 20 * DAY }) });
const step = Array.from({ length: 56 }, (_, i) => sample(i, i < 28 ? 10 : 16));
const stepped = focusedReview(sensor(step), t, step.at(-1)!.t);
assert.equal(stepped.proposals.length, 1);
assert.equal(stepped.proposals[0].changes[0].delta, 6);
assert.equal(ironingOffset(stepped.proposals, "HeightDisplacement", t, step.at(-1)!.t), 6);
assert.equal(ironingOffset(stepped.proposals, "HeightDisplacement", step.at(-1)!.t, step.at(-1)!.t), 0);
assert.equal(ironingOffset(stepped.proposals, "HeightDisplacement", step.at(-1)!.t, t), -6);
assert.equal(focusedReview(sensor(step, [event(t + 7 * DAY, 16)]), t, step.at(-1)!.t).proposals.length, 0);
assert.equal(focusedReview(sensor(Array.from({ length: 56 }, (_, i) => sample(i, 10 + i))), t, t + 14 * DAY).proposals.length, 0);
const oneOutlier = Array.from({ length: 56 }, (_, i) => sample(i, i === 28 ? 100 : 10));
assert.equal(focusedReview(sensor(oneOutlier), t, t + 14 * DAY).proposals.length, 0);
const dailyHole = focusedReview(sensor([sample(0), sample(12)]), t, t + 3 * DAY);
assert.equal(dailyHole.rawGaps.length, 1);
assert.equal(dailyHole.rawGaps[0].from, t + DAY);
assert.equal(dailyHole.rawGaps[0].to, t + 3 * DAY);
const missingMA = focusedReview(sensor([sample(0, 10, null), { ...sample(1, 10, null), suspect: true }]), t, t + DAY);
assert.equal(missingMA.maMissing, 1);
assert.equal(missingMA.maGaps[0].missing, 1);
assert.equal(missingMA.rawGaps.length, 0);
const unsupported = focusedReview({ ...sensor([]), type: "vibration-din", partial: true }, t, t + DAY);
assert.equal(unsupported.supported, false);
assert.equal(unsupported.rawGaps.length, 0);
assert.equal(focusedReview({ ...sensor([]), partial: true, assessedFrom: t + DAY }, t, t + 5 * DAY).from, t + DAY);
assert.equal(focusedReview(sensor([sample(0)]), t - 100 * DAY, t + DAY).rawGaps.length, 0);
console.log("Audit checks passed: baselines, gates, exclusions, real gaps, missing MA, sustained jumps versus drift/outliers, latest-level anchoring, existing corrections and partial scope.");
